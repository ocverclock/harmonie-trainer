 for(const lesson of lessons){
  const items=extraExercises[lesson.id]||[];
  const oldIDs=new Set(lesson.exercises.map(e=>e.id).filter(Boolean));
  for(const item of items){if(!oldIDs.has(item.id)){lesson.exercises.push(item);oldIDs.add(item.id)}}
 }
